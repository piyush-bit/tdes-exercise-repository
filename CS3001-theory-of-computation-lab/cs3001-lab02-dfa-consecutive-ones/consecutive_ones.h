#ifndef CONSECUTIVE_ONES_H
#define CONSECUTIVE_ONES_H

/**
 * Determines whether a given binary string contains at least three consecutive '1's.
 * 
 * @param s Null-terminated input string (binary characters '0' and '1').
 * @return 1 if accepted (contains "111"), 0 if rejected or invalid.
 */
int accepts_three_consecutive_ones(const char *s);

#endif // CONSECUTIVE_ONES_H
